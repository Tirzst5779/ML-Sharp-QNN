package com.sharp.qnn.ui.theme

import androidx.compose.ui.unit.dp

/**
 * MD3 8dp 间距体系。
 * MD3 8dp spacing system.
 *
 * 页面/卡片布局的标准间距统一走此常量, 避免散落的魔数:
 * Page/card layouts use these constants for standard spacing instead of magic numbers:
 * xs=4 / sm=8 / md=12 / lg=16 / xl=24
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
}